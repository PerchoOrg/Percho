export const ANSWER_FORMS = [
  'text',
  'number',
  'map',
  'quote',
  'narrative',
  'timeline',
  'checklist',
  'yes_no',
] as const;
export type AnswerForm = (typeof ANSWER_FORMS)[number];

export type FairHousing = 'n/a' | 'care' | 'never';

export interface QuestionDef {
  id: string;
  theme: QuestionTheme;
  /** Buyer's voice, second person. */
  q: string;
  who: readonly QuestionAudience[];
  scope: QuestionScope;
  basis: readonly BasisType[];
  form: AnswerForm;
  /** "Go see for yourself" template; absent when a visit cannot settle it. */
  verify?: string;
  /** Existing profile dim the question's OPENING feeds, when one fits. */
  dim?: DimKey;
  fh: FairHousing;
}

