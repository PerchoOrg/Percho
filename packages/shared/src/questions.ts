/**
 * The move-in question bank — `docs/design/move-in-questions.md` §3 as data.
 *
 * Shared because both sides read it: the web generation job asks a model to
 * answer these questions for a listing (and validates its output against the
 * allow-lists here), and the mobile explore page renders the question text,
 * groups by theme, and ranks. A question id is a stable contract — events
 * and stored answers reference it — so entries are never renamed, only added.
 *
 * The doc is the source of truth for WHY each row is shaped as it is; this
 * file carries only what code needs. Keep the two in step.
 *
 * Fair Housing (doc §1.3): `fh: 'never'` rows are reserved questions we do
 * not ask. They are listed so the omission is a decision, not an oversight;
 * generation must skip them and the UI must never render them.
 */

